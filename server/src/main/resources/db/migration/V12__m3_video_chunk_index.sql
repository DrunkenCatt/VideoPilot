CREATE TABLE video_index (
    index_id CHAR(36) NOT NULL,
    owner_id VARCHAR(100) NOT NULL,
    source_job_id CHAR(36) NOT NULL,
    context_id CHAR(36) NOT NULL,
    media_id CHAR(36) NOT NULL,
    input_fingerprint CHAR(64) NOT NULL,
    source_digest CHAR(64) NOT NULL,
    chunk_version VARCHAR(64) NOT NULL,
    schema_version VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'BUILDING',
    chunk_count INT UNSIGNED NOT NULL DEFAULT 0,
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL,
    published_at TIMESTAMP(6) NULL,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (index_id),
    UNIQUE KEY uk_video_index_context_input (context_id, input_fingerprint),
    KEY idx_video_index_owner_context_status (owner_id, context_id, status),
    CONSTRAINT fk_video_index_job FOREIGN KEY (source_job_id) REFERENCES analysis_job (job_id),
    CONSTRAINT fk_video_index_context FOREIGN KEY (context_id) REFERENCES video_context (context_id),
    CONSTRAINT fk_video_index_media FOREIGN KEY (media_id) REFERENCES media_asset (media_id),
    CONSTRAINT chk_video_index_status CHECK (status IN ('BUILDING', 'READY', 'SUPERSEDED', 'FAILED')),
    CONSTRAINT chk_video_index_publish CHECK (status <> 'READY' OR published_at IS NOT NULL)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE video_chunk (
    chunk_id CHAR(36) NOT NULL,
    index_id CHAR(36) NOT NULL,
    context_id CHAR(36) NOT NULL,
    media_id CHAR(36) NOT NULL,
    ordinal INT UNSIGNED NOT NULL,
    start_ms BIGINT UNSIGNED NOT NULL,
    end_ms BIGINT UNSIGNED NOT NULL,
    segment_ids JSON NOT NULL,
    summary TEXT NOT NULL,
    keywords JSON NOT NULL,
    asr_text MEDIUMTEXT NOT NULL,
    ocr_text MEDIUMTEXT NOT NULL,
    input_fingerprint CHAR(64) NOT NULL,
    chunk_version VARCHAR(64) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (chunk_id),
    UNIQUE KEY uk_video_chunk_index_ordinal (index_id, ordinal),
    KEY idx_video_chunk_context_window (context_id, start_ms, end_ms),
    CONSTRAINT fk_video_chunk_index FOREIGN KEY (index_id) REFERENCES video_index (index_id),
    CONSTRAINT fk_video_chunk_context FOREIGN KEY (context_id) REFERENCES video_context (context_id),
    CONSTRAINT fk_video_chunk_media FOREIGN KEY (media_id) REFERENCES media_asset (media_id),
    CONSTRAINT chk_video_chunk_window CHECK (end_ms > start_ms)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;
