CREATE TABLE media_asset (
    media_id CHAR(36) NOT NULL,
    owner_id VARCHAR(100) NOT NULL,
    media_fingerprint CHAR(64) NOT NULL,
    object_key VARCHAR(1024) NOT NULL,
    original_filename VARCHAR(512) NOT NULL,
    media_status VARCHAR(32) NOT NULL,
    duration_ms BIGINT UNSIGNED NULL,
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (media_id),
    UNIQUE KEY uk_media_owner_fingerprint (owner_id, media_fingerprint)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE analysis_job (
    job_id CHAR(36) NOT NULL,
    owner_id VARCHAR(100) NOT NULL,
    media_id CHAR(36) NOT NULL,
    analysis_key VARCHAR(128) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    request_fingerprint CHAR(64) NOT NULL,
    goal TEXT NOT NULL,
    mode VARCHAR(32) NOT NULL,
    pipeline_version VARCHAR(64) NOT NULL,
    status VARCHAR(40) NOT NULL,
    current_stage VARCHAR(40) NULL,
    attempt INT UNSIGNED NOT NULL DEFAULT 0,
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    event_sequence BIGINT UNSIGNED NOT NULL DEFAULT 0,
    error_category VARCHAR(32) NULL,
    error_code VARCHAR(100) NULL,
    error_summary VARCHAR(1000) NULL,
    retryable BOOLEAN NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    completed_at TIMESTAMP(6) NULL,
    PRIMARY KEY (job_id),
    UNIQUE KEY uk_job_owner_analysis (owner_id, analysis_key),
    UNIQUE KEY uk_job_owner_idempotency (owner_id, idempotency_key),
    KEY idx_job_media (media_id),
    KEY idx_job_status_updated (status, updated_at),
    CONSTRAINT fk_job_media FOREIGN KEY (media_id) REFERENCES media_asset (media_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE job_stage_attempt (
    stage_attempt_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    job_id CHAR(36) NOT NULL,
    stage VARCHAR(40) NOT NULL,
    input_fingerprint VARCHAR(128) NOT NULL,
    checkpoint_schema_version INT UNSIGNED NOT NULL,
    checkpoint_payload JSON NULL,
    artifact_ref VARCHAR(1024) NULL,
    artifact_digest CHAR(64) NULL,
    status VARCHAR(32) NOT NULL,
    attempt INT UNSIGNED NOT NULL DEFAULT 1,
    error_category VARCHAR(32) NULL,
    error_code VARCHAR(100) NULL,
    error_summary VARCHAR(1000) NULL,
    started_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    completed_at TIMESTAMP(6) NULL,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (stage_attempt_id),
    UNIQUE KEY uk_stage_input (job_id, stage, input_fingerprint),
    KEY idx_stage_job_status (job_id, status),
    CONSTRAINT fk_stage_job FOREIGN KEY (job_id) REFERENCES analysis_job (job_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE job_event_outbox (
    outbox_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    message_id CHAR(36) NOT NULL,
    job_id CHAR(36) NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    schema_version INT UNSIGNED NOT NULL,
    job_sequence BIGINT UNSIGNED NOT NULL,
    request_id VARCHAR(100) NOT NULL,
    payload JSON NOT NULL,
    publish_status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    publish_attempts INT UNSIGNED NOT NULL DEFAULT 0,
    available_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    published_at TIMESTAMP(6) NULL,
    last_error_summary VARCHAR(1000) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (outbox_id),
    UNIQUE KEY uk_outbox_message (message_id),
    UNIQUE KEY uk_outbox_job_sequence (job_id, job_sequence),
    KEY idx_outbox_publish_ready (publish_status, available_at),
    CONSTRAINT fk_outbox_job FOREIGN KEY (job_id) REFERENCES analysis_job (job_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE model_call (
    model_call_id CHAR(36) NOT NULL,
    job_id CHAR(36) NOT NULL,
    run_id CHAR(36) NULL,
    request_id VARCHAR(100) NOT NULL,
    operation_type VARCHAR(64) NOT NULL,
    provider VARCHAR(64) NOT NULL,
    model_name VARCHAR(128) NOT NULL,
    model_version VARCHAR(128) NOT NULL,
    prompt_version VARCHAR(64) NULL,
    embedding_version VARCHAR(64) NULL,
    input_fingerprint VARCHAR(128) NOT NULL,
    output_artifact_ref VARCHAR(1024) NULL,
    status VARCHAR(32) NOT NULL,
    attempt INT UNSIGNED NOT NULL DEFAULT 1,
    error_category VARCHAR(32) NULL,
    error_code VARCHAR(100) NULL,
    error_summary VARCHAR(1000) NULL,
    input_units BIGINT UNSIGNED NULL,
    output_units BIGINT UNSIGNED NULL,
    estimated_cost DECIMAL(19, 8) NULL,
    currency CHAR(3) NULL,
    price_version VARCHAR(64) NULL,
    latency_ms BIGINT UNSIGNED NULL,
    started_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    completed_at TIMESTAMP(6) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (model_call_id),
    KEY idx_model_call_job (job_id, created_at),
    KEY idx_model_call_run (run_id, created_at),
    KEY idx_model_call_fingerprint (job_id, operation_type, input_fingerprint),
    CONSTRAINT fk_model_call_job FOREIGN KEY (job_id) REFERENCES analysis_job (job_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;
