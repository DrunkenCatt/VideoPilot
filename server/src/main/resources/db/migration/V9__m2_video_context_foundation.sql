CREATE TABLE video_context (
    context_id CHAR(36) NOT NULL,
    source_job_id CHAR(36) NOT NULL,
    media_id CHAR(36) NOT NULL,
    input_fingerprint CHAR(64) NOT NULL,
    pipeline_version VARCHAR(64) NOT NULL,
    extraction_version VARCHAR(64) NOT NULL,
    alignment_version VARCHAR(64) NOT NULL,
    duration_ms BIGINT UNSIGNED NOT NULL,
    status VARCHAR(32) NOT NULL,
    asr_state VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    ocr_state VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    segment_count INT UNSIGNED NOT NULL DEFAULT 0,
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    completed_at TIMESTAMP(6) NULL,
    PRIMARY KEY (context_id),
    UNIQUE KEY uk_context_media_input (media_id, input_fingerprint),
    KEY idx_context_source_job (source_job_id),
    CONSTRAINT fk_context_source_job FOREIGN KEY (source_job_id) REFERENCES analysis_job (job_id),
    CONSTRAINT fk_context_media FOREIGN KEY (media_id) REFERENCES media_asset (media_id),
    CONSTRAINT chk_context_status CHECK (status IN ('BUILDING', 'READY', 'FAILED', 'CANCELED')),
    CONSTRAINT chk_context_asr_state CHECK (asr_state IN ('PENDING', 'AVAILABLE', 'FAILED')),
    CONSTRAINT chk_context_ocr_state CHECK (ocr_state IN ('PENDING', 'AVAILABLE', 'DEGRADED', 'FAILED'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE context_work_item (
    work_item_id CHAR(36) NOT NULL,
    media_id CHAR(36) NOT NULL,
    created_by_job_id CHAR(36) NOT NULL,
    kind VARCHAR(32) NOT NULL,
    ordinal INT UNSIGNED NOT NULL,
    start_ms BIGINT UNSIGNED NOT NULL,
    end_ms BIGINT UNSIGNED NOT NULL,
    input_fingerprint CHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    attempt INT UNSIGNED NOT NULL DEFAULT 0,
    claim_id CHAR(36) NULL,
    checkpoint_schema_version INT UNSIGNED NOT NULL DEFAULT 1,
    checkpoint_payload JSON NULL,
    artifact_ref VARCHAR(1024) NULL,
    artifact_digest CHAR(64) NULL,
    error_category VARCHAR(32) NULL,
    error_code VARCHAR(100) NULL,
    error_summary VARCHAR(1000) NULL,
    retryable BOOLEAN NULL,
    version BIGINT UNSIGNED NOT NULL DEFAULT 0,
    started_at TIMESTAMP(6) NULL,
    completed_at TIMESTAMP(6) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (work_item_id),
    UNIQUE KEY uk_work_item_media_input (media_id, kind, input_fingerprint),
    KEY idx_work_item_job_status (created_by_job_id, status),
    KEY idx_work_item_recovery (status, updated_at),
    CONSTRAINT fk_work_item_media FOREIGN KEY (media_id) REFERENCES media_asset (media_id),
    CONSTRAINT fk_work_item_job FOREIGN KEY (created_by_job_id) REFERENCES analysis_job (job_id),
    CONSTRAINT chk_work_item_kind CHECK (kind IN ('AUDIO_SLICE', 'KEYFRAME')),
    CONSTRAINT chk_work_item_status CHECK (status IN ('PENDING', 'STARTED', 'COMPLETED', 'FAILED', 'UNKNOWN', 'CANCELED')),
    CONSTRAINT chk_work_item_window CHECK (end_ms > start_ms),
    CONSTRAINT chk_work_item_completion CHECK (
        status <> 'COMPLETED'
        OR (artifact_ref IS NOT NULL AND artifact_digest IS NOT NULL AND checkpoint_payload IS NOT NULL AND completed_at IS NOT NULL)
    )
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE video_segment (
    segment_id CHAR(36) NOT NULL,
    context_id CHAR(36) NOT NULL,
    ordinal INT UNSIGNED NOT NULL,
    start_ms BIGINT UNSIGNED NOT NULL,
    end_ms BIGINT UNSIGNED NOT NULL,
    asr_text TEXT NULL,
    ocr_observations JSON NOT NULL,
    keyframes JSON NOT NULL,
    content_digest CHAR(64) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (segment_id),
    UNIQUE KEY uk_segment_context_ordinal (context_id, ordinal),
    KEY idx_segment_context_window (context_id, start_ms, end_ms),
    CONSTRAINT fk_segment_context FOREIGN KEY (context_id) REFERENCES video_context (context_id),
    CONSTRAINT chk_segment_window CHECK (end_ms > start_ms)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;
